-- Additive connected-platform schema. Legacy prototype tables are preserved.
CREATE TABLE IF NOT EXISTS rs_users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(140) NOT NULL,
 phone VARCHAR(24) NOT NULL UNIQUE, email VARCHAR(190) NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'active', contact_status VARCHAR(24) NOT NULL DEFAULT 'unverified',
 locale VARCHAR(12) NOT NULL DEFAULT 'en-BD', preferences JSON NOT NULL, totp_secret VARCHAR(80) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, version INT NOT NULL DEFAULT 1
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_roles (
 user_id BIGINT UNSIGNED NOT NULL, role_key VARCHAR(32) NOT NULL, expires_at DATETIME NULL,
 PRIMARY KEY(user_id,role_key), FOREIGN KEY(user_id) REFERENCES rs_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_sessions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 token_hash CHAR(64) NOT NULL UNIQUE, csrf CHAR(64) NOT NULL, device_label VARCHAR(100) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, seen_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at DATETIME NOT NULL, revoked_at DATETIME NULL, mfa_at DATETIME NULL,
 FOREIGN KEY(user_id) REFERENCES rs_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_rate_limits (
 bucket CHAR(64) PRIMARY KEY, hits INT NOT NULL DEFAULT 1, reset_at DATETIME NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_settings (
 setting_key VARCHAR(64) PRIMARY KEY, value_json JSON NOT NULL, version INT NOT NULL DEFAULT 1,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_key VARCHAR(32) NOT NULL UNIQUE,
 name VARCHAR(80) NOT NULL, description VARCHAR(240) NOT NULL, capacity INT NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, rate_minor INT NOT NULL DEFAULT 10000,
 driver_share_bps INT NOT NULL DEFAULT 10000, requirements JSON NOT NULL, version INT NOT NULL DEFAULT 1
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_places (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(160) NOT NULL, address VARCHAR(240) NOT NULL,
 lat DECIMAL(10,7) NOT NULL, lng DECIMAL(10,7) NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_saved_places (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 label VARCHAR(80) NOT NULL, place_json JSON NOT NULL, FOREIGN KEY(user_id) REFERENCES rs_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_drivers (
 user_id BIGINT UNSIGNED PRIMARY KEY, status VARCHAR(24) NOT NULL DEFAULT 'pending',
 desired_online BOOLEAN NOT NULL DEFAULT FALSE, heartbeat_at DATETIME NULL,
 location_json JSON NULL, online_since DATETIME NULL, work_seconds INT NOT NULL DEFAULT 0,
 rest_until DATETIME NULL, identity_status VARCHAR(24) NOT NULL DEFAULT 'pending',
 active_vehicle_id BIGINT UNSIGNED NULL, reason VARCHAR(240) NULL, version INT NOT NULL DEFAULT 1,
 FOREIGN KEY(user_id) REFERENCES rs_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_vehicles (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, driver_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL, label VARCHAR(140) NOT NULL, plate VARCHAR(40) NOT NULL UNIQUE,
 capacity INT NOT NULL, equipment JSON NOT NULL, status VARCHAR(24) NOT NULL DEFAULT 'pending',
 FOREIGN KEY(driver_id) REFERENCES rs_users(id), FOREIGN KEY(product_id) REFERENCES rs_products(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_documents (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 vehicle_id BIGINT UNSIGNED NULL, kind VARCHAR(32) NOT NULL, storage_key VARCHAR(160) NOT NULL,
 mime VARCHAR(80) NOT NULL, checksum CHAR(64) NOT NULL, status VARCHAR(24) NOT NULL DEFAULT 'pending',
 expires_at DATETIME NULL, reason VARCHAR(240) NULL, reviewed_by BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, version INT NOT NULL DEFAULT 1,
 FOREIGN KEY(user_id) REFERENCES rs_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_terms (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, kind VARCHAR(40) NOT NULL, version VARCHAR(32) NOT NULL,
 title VARCHAR(160) NOT NULL, body TEXT NOT NULL, effective_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(kind,version)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_consents (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, terms_id BIGINT UNSIGNED NOT NULL,
 accepted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, withdrawn_at DATETIME NULL,
 UNIQUE(user_id,terms_id), FOREIGN KEY(user_id) REFERENCES rs_users(id), FOREIGN KEY(terms_id) REFERENCES rs_terms(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_quotes (
 id CHAR(32) PRIMARY KEY, customer_id BIGINT UNSIGNED NOT NULL, product_id BIGINT UNSIGNED NOT NULL,
 pickup JSON NOT NULL, destination JSON NOT NULL, stops JSON NOT NULL, needs JSON NOT NULL,
 distance_m INT NOT NULL, route_source VARCHAR(40) NOT NULL, route_json JSON NOT NULL,
 rate_minor INT NOT NULL, fare_minor INT NOT NULL, discount_minor INT NOT NULL DEFAULT 0,
 product_version INT NOT NULL, terms_id BIGINT UNSIGNED NOT NULL, promo_id BIGINT UNSIGNED NULL,
 expires_at DATETIME NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(customer_id) REFERENCES rs_users(id), FOREIGN KEY(product_id) REFERENCES rs_products(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_trips (
 id CHAR(32) PRIMARY KEY, customer_id BIGINT UNSIGNED NOT NULL, driver_id BIGINT UNSIGNED NULL,
 vehicle_id BIGINT UNSIGNED NULL, quote_id CHAR(32) NOT NULL UNIQUE, status VARCHAR(24) NOT NULL,
 snapshot JSON NOT NULL, fare_minor INT NOT NULL, earning_minor INT NOT NULL DEFAULT 0,
 pin_hash VARCHAR(255) NOT NULL, pin_encrypted TEXT NOT NULL, pin_required BOOLEAN NOT NULL,
 pin_attempts INT NOT NULL DEFAULT 0, payment_status VARCHAR(24) NOT NULL DEFAULT 'uncollected',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, accepted_at DATETIME NULL, arrived_at DATETIME NULL,
 started_at DATETIME NULL, ended_at DATETIME NULL, version INT NOT NULL DEFAULT 1,
 FOREIGN KEY(customer_id) REFERENCES rs_users(id), FOREIGN KEY(driver_id) REFERENCES rs_users(id),
 FOREIGN KEY(quote_id) REFERENCES rs_quotes(id), INDEX(customer_id,created_at), INDEX(driver_id,status)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_active (
 actor_type VARCHAR(16) NOT NULL, actor_id BIGINT UNSIGNED NOT NULL, trip_id CHAR(32) NOT NULL,
 PRIMARY KEY(actor_type,actor_id), FOREIGN KEY(trip_id) REFERENCES rs_trips(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_offers (
 id CHAR(32) PRIMARY KEY, trip_id CHAR(32) NOT NULL, driver_id BIGINT UNSIGNED NOT NULL,
 vehicle_id BIGINT UNSIGNED NOT NULL, status VARCHAR(24) NOT NULL DEFAULT 'pending',
 expires_at DATETIME NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(trip_id) REFERENCES rs_trips(id), FOREIGN KEY(driver_id) REFERENCES rs_users(id),
 UNIQUE(trip_id,driver_id), INDEX(driver_id,status,expires_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, trip_id CHAR(32) NOT NULL, actor_id BIGINT UNSIGNED NULL,
 event_key VARCHAR(48) NOT NULL, details JSON NOT NULL, request_id VARCHAR(64) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(trip_id) REFERENCES rs_trips(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_operations (
 user_id BIGINT UNSIGNED NOT NULL, operation_key VARCHAR(80) NOT NULL, action_key VARCHAR(48) NOT NULL,
 body_hash CHAR(64) NOT NULL, response_json JSON NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,operation_key)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_messages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, trip_id CHAR(32) NOT NULL, sender_id BIGINT UNSIGNED NOT NULL,
 body VARCHAR(2000) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(trip_id) REFERENCES rs_trips(id), FOREIGN KEY(sender_id) REFERENCES rs_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_ratings (
 trip_id CHAR(32) NOT NULL, actor_id BIGINT UNSIGNED NOT NULL, rating INT NOT NULL, feedback VARCHAR(1000) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(trip_id,actor_id),
 FOREIGN KEY(trip_id) REFERENCES rs_trips(id), FOREIGN KEY(actor_id) REFERENCES rs_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_journals (
 id CHAR(32) PRIMARY KEY, trip_id CHAR(32) NULL, kind VARCHAR(32) NOT NULL,
 reference_key VARCHAR(120) NOT NULL UNIQUE, actor_id BIGINT UNSIGNED NOT NULL,
 evidence VARCHAR(500) NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_entries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, journal_id CHAR(32) NOT NULL,
 account_key VARCHAR(80) NOT NULL, user_id BIGINT UNSIGNED NULL, amount_minor BIGINT NOT NULL,
 FOREIGN KEY(journal_id) REFERENCES rs_journals(id), INDEX(user_id,account_key)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_cases (
 id CHAR(32) PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, trip_id CHAR(32) NULL,
 category VARCHAR(40) NOT NULL, subject VARCHAR(160) NOT NULL, priority VARCHAR(24) NOT NULL DEFAULT 'normal',
 status VARCHAR(24) NOT NULL DEFAULT 'open', owner_id BIGINT UNSIGNED NULL, restricted BOOLEAN NOT NULL DEFAULT FALSE,
 due_at DATETIME NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, version INT NOT NULL DEFAULT 1,
 FOREIGN KEY(user_id) REFERENCES rs_users(id), FOREIGN KEY(trip_id) REFERENCES rs_trips(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_case_messages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, case_id CHAR(32) NOT NULL, actor_id BIGINT UNSIGNED NOT NULL,
 body VARCHAR(4000) NOT NULL, internal_note BOOLEAN NOT NULL DEFAULT FALSE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(case_id) REFERENCES rs_cases(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_exclusions (
 customer_id BIGINT UNSIGNED NOT NULL, driver_id BIGINT UNSIGNED NOT NULL, case_id CHAR(32) NOT NULL,
 expires_at DATETIME NOT NULL, reason VARCHAR(240) NOT NULL, actor_id BIGINT UNSIGNED NOT NULL,
 revoked_at DATETIME NULL, PRIMARY KEY(customer_id,driver_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 category VARCHAR(32) NOT NULL, title VARCHAR(160) NOT NULL, body VARCHAR(1000) NOT NULL,
 target_id VARCHAR(40) NULL, read_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES rs_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_shares (
 token_hash CHAR(64) PRIMARY KEY, trip_id CHAR(32) NOT NULL, created_by BIGINT UNSIGNED NOT NULL,
 expires_at DATETIME NOT NULL, revoked_at DATETIME NULL, FOREIGN KEY(trip_id) REFERENCES rs_trips(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_requests (
 id CHAR(32) PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, kind VARCHAR(48) NOT NULL,
 trip_id CHAR(32) NULL, payload JSON NOT NULL, status VARCHAR(32) NOT NULL DEFAULT 'pending',
 reason VARCHAR(500) NULL, owner_id BIGINT UNSIGNED NULL, approved_by BIGINT UNSIGNED NULL,
 proposal_hash CHAR(64) NOT NULL, version INT NOT NULL DEFAULT 1, expires_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, executed_at DATETIME NULL,
 FOREIGN KEY(user_id) REFERENCES rs_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actor_id BIGINT UNSIGNED NULL,
 action_key VARCHAR(80) NOT NULL, entity_id VARCHAR(80) NOT NULL, reason VARCHAR(500) NOT NULL,
 before_json JSON NULL, after_json JSON NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_contacts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(100) NOT NULL, phone VARCHAR(24) NOT NULL, purpose VARCHAR(24) NOT NULL,
 consented_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(user_id) REFERENCES rs_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_profiles (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(80) NOT NULL, kind VARCHAR(24) NOT NULL, policy_json JSON NOT NULL,
 FOREIGN KEY(user_id) REFERENCES rs_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_promos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(32) NOT NULL UNIQUE,
 description VARCHAR(240) NOT NULL, discount_minor INT NOT NULL, maximum_uses INT NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, expires_at DATETIME NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_redemptions (
 promo_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL, trip_id CHAR(32) NOT NULL,
 PRIMARY KEY(promo_id,user_id), FOREIGN KEY(trip_id) REFERENCES rs_trips(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_request_results (
 request_id CHAR(32) PRIMARY KEY, result_json JSON NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(request_id) REFERENCES rs_requests(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_trip_changes (
 id CHAR(32) PRIMARY KEY, trip_id CHAR(32) NOT NULL, customer_id BIGINT UNSIGNED NOT NULL,
 trip_version INT NOT NULL, before_json JSON NOT NULL, after_json JSON NOT NULL,
 fare_minor INT NOT NULL, status VARCHAR(24) NOT NULL DEFAULT 'quoted',
 expires_at DATETIME NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(trip_id) REFERENCES rs_trips(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_intakes (
 id CHAR(32) PRIMARY KEY, access_hash CHAR(64) NOT NULL, kind VARCHAR(24) NOT NULL,
 contact_encrypted TEXT NOT NULL, message_encrypted TEXT NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'pending', public_reply VARCHAR(2000) NULL,
 owner_id BIGINT UNSIGNED NULL, version INT NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rs_recovery_grants (
 intake_id CHAR(32) PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 expires_at DATETIME NOT NULL, used_at DATETIME NULL,
 FOREIGN KEY(intake_id) REFERENCES rs_intakes(id), FOREIGN KEY(user_id) REFERENCES rs_users(id)
) ENGINE=InnoDB;
