"""Reproducible Dhaka road subset. Derived OSM databases remain under ODbL 1.0."""
from pathlib import Path
import sys, json, hashlib
root=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(root/'.tools/python-maps'))
import osmium
directory=root/'.local/routing'
ways=set();nodes=set();roads=[]
bounds=[90.2,23.6,90.6,24.0]
class Select(osmium.SimpleHandler):
 def way(self,w):
  if not w.tags.get('highway'):return
  coords=[(n.lon,n.lat) for n in w.nodes if n.location.valid()]
  if len(coords)<2 or not any(bounds[0]<=x<=bounds[2] and bounds[1]<=y<=bounds[3] for x,y in coords):return
  ways.add(w.id);nodes.update(n.ref for n in w.nodes)
  roads.append({'id':w.id,'kind':w.tags.get('highway'),'name':w.tags.get('name',''),'bounds':[min(x for x,y in coords),min(y for x,y in coords),max(x for x,y in coords),max(y for x,y in coords)],'points':[[round(x,6),round(y,6)] for x,y in coords]})
print('Selecting Dhaka roads',flush=True)
Select().apply_file(str(directory/'bangladesh.osm.pbf'),locations=True,idx='flex_mem')
target=directory/'dhaka.osm.pbf'
if target.exists():target.unlink()
with osmium.SimpleWriter(str(target)) as writer:
 class Write(osmium.SimpleHandler):
  def node(self,n):
   if n.id in nodes:writer.add_node(n)
  def way(self,w):
   if w.id in ways:writer.add_way(w)
  def relation(self,r):
   if r.tags.get('type')=='restriction' and all(m.ref in (ways if m.type=='w' else nodes) for m in r.members):writer.add_relation(r)
 Write().apply_file(str(directory/'bangladesh.osm.pbf'))
asset=root/'mobile/assets/maps';asset.mkdir(parents=True,exist_ok=True)
data={'bounds':bounds,'attribution':'© OpenStreetMap contributors','license':'ODbL 1.0','source':'https://download.geofabrik.de/asia/bangladesh.html','source_sha256':hashlib.file_digest((directory/'bangladesh.osm.pbf').open('rb'),'sha256').hexdigest(),'roads':roads}
(asset/'dhaka-roads.json').write_text(json.dumps(data,separators=(',',':'),ensure_ascii=False),encoding='utf-8')
(asset/'LICENSE.txt').write_text('Dhaka road extract and vector database © OpenStreetMap contributors.\nLicensed under Open Data Commons Open Database License (ODbL) 1.0.\nhttps://opendatacommons.org/licenses/odbl/1-0/\nhttps://www.openstreetmap.org/copyright\nSource: Geofabrik Bangladesh extract, downloaded 2026-10-11.\nComplete derived vector database is supplied as dhaka-roads.json.\nRouting extract is generated by tools/extract_maps.py from the same source.\n',encoding='utf-8')
print(f'Extracted {len(ways)} roads / {len(nodes)} nodes; routing bytes {target.stat().st_size}',flush=True)
